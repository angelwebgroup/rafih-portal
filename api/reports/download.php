<?php
require_once __DIR__ . '/../helpers.php';
require_once __DIR__ . '/../db.php';

// Handle CORS
ApiResponse::cors();

RequestHelper::requireMethod('GET');

try {
    // Require authentication
    $user = RequestHelper::requireAuth();
    
    // Get report/export ID from URL
    $reportId = $_GET['id'] ?? '';
    
    if (empty($reportId)) {
        ApiResponse::error('Report ID is required', 400);
    }
    
    // In a real implementation, you would:
    // 1. Look up the report/export in the database
    // 2. Verify the user has permission to download it
    // 3. Check if the file exists
    // 4. Stream the file to the user
    
    // For this demo, we'll simulate a file download
    $filename = 'report_' . $reportId . '.pdf';
    $filepath = __DIR__ . '/../../storage/reports/' . $filename;
    
    // Check if this is a simulated download (for demo purposes)
    if (!file_exists($filepath)) {
        // Generate a sample PDF content for demonstration
        $sampleContent = generateSampleReportContent($reportId, $user);
        
        // Set appropriate headers for PDF download
        header('Content-Type: application/pdf');
        header('Content-Disposition: attachment; filename="' . $filename . '"');
        header('Content-Length: ' . strlen($sampleContent));
        header('Cache-Control: no-cache, must-revalidate');
        header('Expires: Sat, 26 Jul 1997 05:00:00 GMT');
        
        // Output the content
        echo $sampleContent;
        exit;
    }
    
    // If file exists, serve it
    if (file_exists($filepath)) {
        $filesize = filesize($filepath);
        $mimetype = mime_content_type($filepath);
        
        // Set headers for file download
        header('Content-Type: ' . $mimetype);
        header('Content-Disposition: attachment; filename="' . basename($filename) . '"');
        header('Content-Length: ' . $filesize);
        header('Cache-Control: no-cache, must-revalidate');
        header('Expires: Sat, 26 Jul 1997 05:00:00 GMT');
        
        // Read and output the file
        readfile($filepath);
        exit;
    } else {
        ApiResponse::notFound('Report file not found');
    }
    
} catch (Exception $e) {
    error_log("Report download error: " . $e->getMessage());
    ApiResponse::error('Failed to download report: ' . $e->getMessage(), 500);
}

